function getCheckpointIndex(level) {
    return Math.floor((Math.max(1, parseInt(level) || 1) - 1) / 5);
}

function getTheme(arg1, arg2) {
    if (arguments.length === 1) {
        var cpOnly = getCheckpointIndex(arg1);
        return themeList[cpOnly % themeList.length];
    }
    var mode = parseInt(arg1);
    if (isNaN(mode)) mode = 1;
    var level = parseInt(arg2) || 1;
    var cpIndex = getCheckpointIndex(level);

    if (mode === 0) {
        return themeList[cpIndex % themeList.length];
    }
    var selected = ((mode - 1) + cpIndex) % themeList.length;
    if (selected < 0) selected = 0;
    return themeList[selected];
}

function getThemeName(themeMode, levelNum) {
    var mode = parseInt(themeMode);
    if (isNaN(mode)) mode = 1;
    var theme = getTheme(mode, levelNum);
    if (mode === 0) {
        return "Dynamic (" + theme.name + ")";
    }
    return theme.name;
}

function lerpColor(c1, c2, t) {
    if (!c1) return c2 || "#000000";
    if (!c2) return c1 || "#000000";
    if (t <= 0.0) return c1;
    if (t >= 1.0) return c2;

    var r1 = parseInt(c1.slice(1, 3), 16) || 0;
    var g1 = parseInt(c1.slice(3, 5), 16) || 0;
    var b1 = parseInt(c1.slice(5, 7), 16) || 0;

    var r2 = parseInt(c2.slice(1, 3), 16) || 0;
    var g2 = parseInt(c2.slice(3, 5), 16) || 0;
    var b2 = parseInt(c2.slice(5, 7), 16) || 0;

    var r = Math.round(r1 + (r2 - r1) * t);
    var g = Math.round(g1 + (g2 - g1) * t);
    var b = Math.round(b1 + (b2 - b1) * t);

    return "rgb(" + r + "," + g + "," + b + ")";
}
